# nanopore_converter.py
# --------------------------------------------------------------------------

def test_converter_mixed_run_keeps_every_read(tmp_path):
    run_dir = tmp_path / "20200101_mixed"
    singles(run_dir / "fast5_pass", 12)
    multi(run_dir / "fast5_fail", 8, tmp_path, start=100)
    res = run([CONVERTER, run_dir, "--output-dir", tmp_path / "out"])
    assert res.returncode == 0, res.stderr
    assert pod5_reads(tmp_path / "out" / "20200101_mixed" / "pod5") == 20
    assert "Verified 20 reads" in res.stderr


def test_converter_skips_corrupt_file_and_reports_it(tmp_path):
    run_dir = tmp_path / "20200101_trunc"
    multi(run_dir / "fast5_pass", 10, tmp_path)
    good = next((run_dir / "fast5_pass").glob("*.fast5"))
    (run_dir / "fast5_pass" / "aaa_truncated.fast5").write_bytes(good.read_bytes()[:3000])
    res = run([CONVERTER, run_dir, "--output-dir", tmp_path / "out"])
    assert res.returncode == 0, res.stderr
    assert pod5_reads(tmp_path / "out" / "20200101_trunc" / "pod5") == 10
    assert "aaa_truncated.fast5" in res.stderr
    assert "1 unreadable/corrupt fast5 file(s) were not converted" in res.stderr


def test_converter_fills_metadata_from_context_tags(tmp_path):
    """Flowcell only in context_tags: pod5 convert drops it, the converter
    fills it so dorado's automatic model selection works."""
    run_dir = tmp_path / "20180601_ctx"
    for i in range(5):
        f = single_read_fast5(run_dir / "fast5_pass" / f"r{i}.fast5", i)
        with h5py.File(f, "a") as h:
            del h["UniqueGlobalKey/tracking_id"].attrs["flow_cell_product_code"]
            h["UniqueGlobalKey/context_tags"].attrs["flowcell_type"] = b"flo-min106"
    res = run([CONVERTER, run_dir, "--output-dir", tmp_path / "out"])
    assert res.returncode == 0, res.stderr
    with pod5.Reader(next((tmp_path / "out" / "20180601_ctx" / "pod5").glob("*.pod5"))) as r:
        info = next(r.reads()).run_info
        assert info.flow_cell_product_code.upper() == "FLO-MIN106"
        assert info.sequencing_kit.upper() == "SQK-LSK109"


