def test_generated_script_end_to_end(tmp_path):
    runs = tmp_path / "runs"
    singles(runs / "20190501_single" / "fast5_pass" / "0", 15)
    multi(runs / "20230101_multi" / "fast5_pass", 9, tmp_path)
    # mixed run: the script cannot convert it fully and must say so
    singles(runs / "20200101_mixed" / "fast5_pass", 4)
    multi(runs / "20200101_mixed" / "fast5_fail", 3, tmp_path, start=50)
    script = tmp_path / "convert.sh"
    res = run([CHECKER, runs, "--convert-to", "pod5", "--script-output", script])
    assert res.returncode == 0, res.stderr

    first = subprocess.run(["bash", str(script)], capture_output=True, text=True, cwd="/")
    assert first.returncode == 1  # the mixed run fails ...
    assert "1 run(s) failed: 20200101_mixed" in first.stderr
    # ... but the other runs are converted in place and verified
    assert pod5_reads(runs / "20190501_single" / "pod5_from_fast5") == 15
    assert pod5_reads(runs / "20230101_multi" / "pod5_from_fast5") == 9
    assert not (runs / "20200101_mixed" / "pod5_from_fast5").exists()
    assert not (runs / "20200101_mixed" / ".convert_tmp").exists()

    # Re-running skips finished runs and only retries the failed one
    second = subprocess.run(["bash", str(script)], capture_output=True, text=True)
    assert "Skipping 20190501_single" in second.stdout
    assert "Skipping 20230101_multi" in second.stdout
    assert pod5_reads(runs / "20190501_single" / "pod5_from_fast5") == 15

    # Re-checking does not schedule the converted runs again
    script2 = tmp_path / "convert2.sh"
    run([CHECKER, runs, "--convert-to", "pod5", "--script-output", script2])
    third = subprocess.run(["bash", str(script2)], capture_output=True, text=True)
    assert "Skipping 20190501_single" in third.stdout
    assert pod5_reads(runs / "20190501_single" / "pod5_from_fast5") == 15

    # The converted output carries the source chemistry
    tsv = tmp_path / "s.tsv"
    run([CHECKER, runs, "-o", tsv])
    rows = [r.split("\t") for r in tsv.read_text().splitlines()]
    header, body = rows[0], rows[1:]
    single = next(r for r in body if r[0] == "20190501_single" and r[1] == "pod5")
    assert single[header.index("pore_type")] == "R9.4.1"
    assert single[header.index("dorado_version")] == "0.9.6"


def test_generated_script_with_output_dir_and_relative_paths(tmp_path):
    runs = tmp_path / "runs"
    multi(runs / "20230101_multi" / "fast5_pass", 6, tmp_path)
    res = run([CHECKER, "runs", "--convert-to", "pod5", "--output-dir", "out",
               "--script-output", "c.sh"], cwd=tmp_path)
    assert res.returncode == 0, res.stderr
    done = subprocess.run(["bash", str(tmp_path / "c.sh")], capture_output=True,
                          text=True, cwd="/")  # run from somewhere else
    assert done.returncode == 0, done.stderr
    assert pod5_reads(tmp_path / "out" / "20230101_multi" / "pod5") == 6



def test_generated_script_symlinked_folder_and_glob_characters(tmp_path):
    """Round 3: verification followed symlinks differently from the tools,
    and pod5 convert globbed '[' in paths."""
    import os
    runs = tmp_path / "runs"
    multi(tmp_path / "otherdisk" / "barcode01", 5, tmp_path)
    (runs / "20200101_sym" / "fast5_pass").mkdir(parents=True)
    multi(runs / "20200101_sym" / "fast5_pass", 3, tmp_path, start=100)
    os.symlink(tmp_path / "otherdisk" / "barcode01", runs / "20200101_sym" / "fast5_pass" / "barcode01")
    singles(runs / "20200102_run[1]" / "fast5_pass", 4, start=200)
    script = tmp_path / "c.sh"
    assert run([CHECKER, runs, "--convert-to", "pod5", "--script-output", script]).returncode == 0
    res = subprocess.run(["bash", str(script)], capture_output=True, text=True)
    assert res.returncode == 0, res.stdout + res.stderr
    assert pod5_reads(runs / "20200101_sym" / "pod5_from_fast5") == 8
    assert pod5_reads(runs / "20200102_run[1]" / "pod5_from_fast5") == 4
    again = subprocess.run(["bash", str(script)], capture_output=True, text=True)
    assert again.stdout.count("Skipping") == 2
