#!/usr/bin/env python3
"""End-to-end tests with the real conversion tools.

Runs nanopore_converter.py and scripts generated by nanopore_format_checker.py
against realistic fast5 data using the real `single_to_multi_fast5`
(ont_fast5_api) and `pod5` CLIs.  Skipped when the tools are not installed.
"""

import shutil
import subprocess
import sys
import uuid
from pathlib import Path

import pytest

h5py = pytest.importorskip("h5py")
np = pytest.importorskip("numpy")
pod5 = pytest.importorskip("pod5")

pytestmark = pytest.mark.skipif(
    not (shutil.which("pod5") and shutil.which("single_to_multi_fast5")),
    reason="needs the pod5 and single_to_multi_fast5 CLIs",
)

REPO = Path(__file__).resolve().parent
CHECKER = REPO / "nanopore_format_checker.py"
CONVERTER = REPO / "nanopore_converter.py"


def single_read_fast5(path: Path, i: int, flowcell="flo-min106", kit="sqk-lsk109",
                      rate=4000) -> Path:
    """A single-read fast5 with the metadata MinKNOW writes (pod5 accepts it)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with h5py.File(path, "w") as f:
        f.attrs["file_version"] = "2.0"
        r = f.create_group(f"Raw/Reads/Read_{i}")
        for k, v in dict(read_id=str(uuid.uuid4()), read_number=i, start_time=1000 * i,
                         duration=2000, median_before=200.0, start_mux=1).items():
            r.attrs[k] = v
        r.create_dataset("Signal", data=np.random.randint(300, 700, 2000).astype(np.int16))
        u = f.create_group("UniqueGlobalKey")
        c = u.create_group("channel_id")
        for k, v in dict(channel_number="12", digitisation=8192.0, offset=6.0,
                         range=1467.6, sampling_rate=float(rate)).items():
            c.attrs[k] = v
        t = u.create_group("tracking_id")
        for k, v in dict(run_id="a" * 40, flow_cell_id="FAK12345",
                         flow_cell_product_code=flowcell,
                         exp_start_time="2019-05-01T10:00:00Z", sample_id="s1",
                         device_id="MN1", device_type="minion",
                         protocol_run_id=str(uuid.uuid4()), asic_id="1",
                         exp_script_purpose="sequencing_run", hostname="h",
                         protocol_group_id="g", sample_frequency=str(rate),
                         version="3.4.0").items():
            t.attrs[k] = v.encode()
        g = u.create_group("context_tags")
        for k, v in dict(sequencing_kit=kit, sample_frequency=str(rate),
                         experiment_type="genomic_dna").items():
            g.attrs[k] = v.encode()
    return path


def singles(folder: Path, n: int, start: int = 0) -> None:
    for i in range(start, start + n):
        single_read_fast5(folder / f"read_{i}.fast5", i)


def multi(folder: Path, n: int, tmp: Path, start: int = 0) -> None:
    """A real multi-read fast5 made by single_to_multi_fast5."""
    src = tmp / f"_src_{uuid.uuid4().hex[:6]}"
    singles(src, n, start)
    subprocess.run(["single_to_multi_fast5", "-i", str(src), "-s", str(folder),
                    "-n", str(n)], check=True, capture_output=True)
    (folder / "filename_mapping.txt").unlink(missing_ok=True)
    shutil.rmtree(src)


def pod5_reads(folder: Path) -> int:
    total = 0
    for p in folder.rglob("*.pod5"):
        with pod5.Reader(p) as r:
            total += r.num_reads
    return total


def run(cmd, cwd=None):
    return subprocess.run([sys.executable, *map(str, cmd)], capture_output=True,
                          text=True, cwd=cwd)


